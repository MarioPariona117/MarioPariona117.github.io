#!/usr/bin/env node
// Build the PUBLIC copy of Recollection into public/recollection/.
//
// Why this exists
// ---------------
// /recollection used to live only on the `gh-pages` branch, hand-copied. That
// was fragile in two ways:
//
//   1. `npm run deploy` runs `gh-pages -d build`, and gh-pages defaults to
//      `add: false, remove: '.'` — it wipes the branch and copies build/ in.
//      Since recollection/ was not in build/, the next deploy would have
//      silently deleted the live app.
//   2. The copy drifted: saints added in the source repo never reached the
//      deployed site until someone remembered to re-copy by hand.
//
// Putting the output under public/ means CRA copies it into build/ verbatim,
// so it is part of every deploy and can never be orphaned again.
//
// Source of truth is the app in the `best` repo — this only ever reads from
// it, never writes back (same one-way flow as wardrobe.yaml → the HTML views).
//
// Usage:  node scripts/sync-recollection.mjs [--source <dir>]
//         RECOLLECTION_SRC=<dir> node scripts/sync-recollection.mjs
// Runs automatically as part of `npm run build`.

import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile, cp, rm } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const DEST = join(repoRoot, 'public', 'recollection');

const argSource = (() => {
  const i = process.argv.indexOf('--source');
  return i !== -1 ? process.argv[i + 1] : null;
})();

const SOURCE = resolve(
  argSource ||
    process.env.RECOLLECTION_SRC ||
    join(homedir(), 'Work/proj/Personal/best/faith/journal-app')
);

// Files that make up the public app. config.js / auth.js / drive.js are
// deliberately NOT copied: the hosted build runs in local (localStorage) mode,
// where all three are inert, and shipping them meant the live page loaded
// Google's Identity Services script on every visit for no reason.
const FILES = [
  'index.html',
  'styles.css',
  'app.js',
  'store-local.js',
  'saints-data.js',
  'saints-geo.js',
  'manifest.json',
  'sw.js',
];
const DIRS = ['icons'];

// --- index.html: turn the source app into a public build -------------------

function transformIndexHtml(html) {
  let out = html;

  // 1. Declare this a public build. app.js reads the flag and hides the
  //    Journal tab — entries there go to the *visitor's* localStorage with no
  //    sync, so a journal written on someone else's device is stranded.
  //    (To publish your own journal instead, drop this line.)
  out = out.replace(
    'window.RECOLLECTION_LOCAL_MODE = true;',
    'window.RECOLLECTION_LOCAL_MODE = true; window.RECOLLECTION_PUBLIC_MODE = true;'
  );

  // 2. Remove the commented-out Google Drive block wholesale. In the source
  //    it is a parked switch: uncomment those four <script> tags to move from
  //    localStorage to real Drive sync. The public build never takes that
  //    path — config.js / auth.js / drive.js are not even copied — so leaving
  //    the block in would ship a comment pointing at files that 404.
  out = out.replace(
    /<!--\s*\n\s*<script src="https:\/\/accounts\.google\.com\/gsi\/client"[\s\S]*?-->\n?/,
    ''
  );

  // Reword the local-mode note, which in the source describes the switch we
  // just removed.
  out = out.replace(
    /<!-- LOCAL MODE \(default for now\)[\s\S]*?-->/,
    `<!-- PUBLIC BUILD — generated by the portfolio's scripts/sync-recollection.mjs.
     Do not edit here; edit the source app and re-run the script.
     Everything runs in the visitor's own browser: content is seeded from
     saints-data.js and app.js, and anything they change stays in their
     localStorage. No sign-in, no backend, no outbound request. -->`
  );

  return out;
}

// --- sw.js: cache what the public build actually serves ---------------------

function transformServiceWorker(js) {
  let out = js;

  // The shell list still named the three Drive files (now not deployed at all,
  // so `cache.addAll` would reject and the install would fail outright) and
  // omitted saints-geo.js, which the Saints map needs offline.
  out = out.replace(
    /const SHELL_FILES = \[[\s\S]*?\];/,
    `const SHELL_FILES = [
  "./index.html",
  "./styles.css",
  "./app.js",
  "./store-local.js",
  "./saints-data.js",
  "./saints-geo.js",
  "./manifest.json",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
];`
  );

  // Bump the cache name so returning visitors pick the new list up.
  out = out.replace(/recollection-shell-v\d+/, 'recollection-shell-public-v1');

  // The header comment described Drive-API behaviour this build does not have.
  out = out.replace(
    /^\/\/ App-shell caching only[\s\S]*?refreshed on every successful fetch\.\n/m,
    `// App-shell caching for the PUBLIC build of Recollection (generated by the
// portfolio's scripts/sync-recollection.mjs — edit that, not this file).
//
// This build runs entirely in the browser: content is seeded from
// saints-data.js and app.js's SEED_LIBRARY_ENTRIES, and anything a visitor
// changes stays in their own localStorage. There is no backend and no
// outbound request.
//
// Network-first, falling back to cache: always tries the network so edits to
// a shell file show up on next reload with no version bump needed. The cache
// is an offline safety net, refreshed on every successful fetch.\n`
  );

  return out;
}

const TRANSFORMS = {
  'index.html': transformIndexHtml,
  'sw.js': transformServiceWorker,
};

// --- run -------------------------------------------------------------------

async function main() {
  if (!existsSync(SOURCE)) {
    console.error(
      `\n  sync-recollection: source not found\n    ${SOURCE}\n\n` +
        `  Pass --source <dir> or set RECOLLECTION_SRC.\n` +
        `  Skipping — public/recollection/ left as-is.\n`
    );
    // Not fatal: a build on a machine without the `best` repo checked out
    // should still succeed, using whatever is already committed under public/.
    process.exit(existsSync(DEST) ? 0 : 1);
  }

  await rm(DEST, { recursive: true, force: true });
  await mkdir(DEST, { recursive: true });

  for (const name of FILES) {
    const from = join(SOURCE, name);
    if (!existsSync(from)) {
      console.error(`  sync-recollection: missing ${name} in source`);
      process.exit(1);
    }
    const raw = await readFile(from, 'utf8');
    const transform = TRANSFORMS[name];
    await writeFile(join(DEST, name), transform ? transform(raw) : raw);
  }

  for (const dir of DIRS) {
    const from = join(SOURCE, dir);
    if (existsSync(from)) await cp(from, join(DEST, dir), { recursive: true });
  }

  // Verify the transforms actually matched — a silent no-op here would ship a
  // build that still phones Google or still shows the Journal tab.
  const html = await readFile(join(DEST, 'index.html'), 'utf8');
  const problems = [];
  if (!html.includes('RECOLLECTION_PUBLIC_MODE')) problems.push('PUBLIC_MODE flag not injected');
  if (html.includes('accounts.google.com')) problems.push('Google GSI script still present');
  if (html.includes('drive.js')) problems.push('drive.js still referenced');
  if (problems.length) {
    console.error(`\n  sync-recollection: transform failed —\n    ${problems.join('\n    ')}`);
    console.error('  The source app has probably changed shape. Fix the patterns above.\n');
    process.exit(1);
  }

  console.log(`  sync-recollection: public/recollection/ built from ${SOURCE}`);
}

main();
